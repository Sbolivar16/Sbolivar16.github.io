function classifyRepoCategories(repo) {
  const text = `${repo.name} ${repo.description || ""} ${(repo.topics || []).join(" ")}`.toLowerCase();
  const cats = [];
  if (/(dock|vina|gnina|pandadock|3d)/.test(text)) cats.push("docking");
  if (/(gromacs|md|dynamics|mmpbsa|openmm|trajectory)/.test(text)) cats.push("md");
  if (/(qsar|sar|admet|chembl|shap|screening|bioisoster)/.test(text)) cats.push("qsar");
  if (/(cheminform|datamol|rdkit|openbabel|descriptor|chemical space)/.test(text)) cats.push("chem");
  return cats.length ? cats : ["chem"];
}

async function hydrateGitHubStats() {
  try {
    const res = await fetch("https://api.github.com/users/Sbolivar16/repos?per_page=100&sort=pushed");
    if (!res.ok) return;
    const live = await res.json();
    if (!Array.isArray(live)) return;

    let totalStars = 0;
    let totalForks = 0;
    const map = new Map(live.map((r) => [r.name, r]));
    live.forEach((r) => {
      totalStars += r.stargazers_count || 0;
      totalForks += r.forks_count || 0;
    });

    const excluded = new Set(["Sbolivar16", "Sbolivar16.github.io"]);
    const knownNames = new Set(reposData.map((r) => r.name));

    const updatedKnown = reposData.map((r) => {
      const m = map.get(r.name);
      if (!m) return r;
      return {
        ...r,
        stars: m.stargazers_count ?? r.stars,
        forks: m.forks_count ?? r.forks,
        language: m.language || r.language,
        description: m.description || r.description,
      };
    });

    const discovered = live
      .filter((m) => !m.fork && !m.private && !excluded.has(m.name) && !knownNames.has(m.name))
      .map((m) => {
        const cats = classifyRepoCategories(m);
        return {
          name: m.name,
          category: cats[0],
          categories: cats,
          stars: m.stargazers_count || 0,
          forks: m.forks_count || 0,
          language: m.language || "Python",
          description: m.description || "Open-source computational chemistry & drug discovery repository.",
          url: m.html_url,
        };
      });

    reposData = [...discovered, ...updatedKnown];

    document.getElementById("statStars").textContent = String(totalStars);
    document.getElementById("statForks").textContent = String(totalForks);
    renderRepos();
  } catch {
    // Keep verified fallback stats silently
  }
}

function applyMolStyle() {
  if (!viewer) return;
  viewer.removeAllSurfaces();
  viewer.setStyle({}, {});
  if (styleMode === 0) {
    viewer.setStyle({ hetflag: false }, { cartoon: { color: "spectrum", opacity: 0.9 } });
    viewer.setStyle({ hetflag: true, resn: ["HOH"], invert: true }, { stick: { colorscheme: "cyanCarbon", radius: 0.22 } });
  } else if (styleMode === 1) {
    viewer.setStyle({ hetflag: false }, { cartoon: { color: "#38bdf8", opacity: 0.55 } });
    viewer.addSurface($3Dmol.SurfaceType.VDW, { opacity: 0.45, color: "#0f2942" }, { hetflag: false });
    viewer.setStyle({ hetflag: true, resn: ["HOH"], invert: true }, { stick: { colorscheme: "greenCarbon", radius: 0.25 } });
  } else {
    viewer.setStyle({ hetflag: false }, { line: { color: "#64748b" } });
    viewer.setStyle({ hetflag: true, resn: ["HOH"], invert: true }, { stick: { colorscheme: "cyanCarbon", radius: 0.26 } });
  }
  viewer.render();
}

function loadPdb(pdbId) {
  currentPdb = pdbId;
  const statusEl = document.getElementById("viewerStatus");
  if (typeof $3Dmol === "undefined") {
    statusEl.textContent = "3Dmol.js unavailable offline — view repositories below.";
    return;
  }
  statusEl.style.display = "grid";
  statusEl.textContent = `Loading RCSB PDB ${pdbId}…`;
  if (!viewer) {
    viewer = $3Dmol.createViewer(document.getElementById("molViewer"), { backgroundColor: "#07131f" });
  }
  $3Dmol.download(`pdb:${pdbId}`, viewer, {}, () => {
    statusEl.style.display = "none";
    applyMolStyle();
    viewer.zoomTo();
    viewer.zoom(1.05);
    viewer.spin(isSpinning ? "y" : false, 0.35);
    viewer.render();
  });
}

